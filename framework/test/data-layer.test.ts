describe("sql guard", () => {
  test("allows a single SELECT/WITH, refuses writes, DDL, multiple statements, dangerous functions", () => {
    expect(sqlProblem("SELECT count(*) FROM tb_place_info WHERE sido = '경기'")).toBeNull()
    expect(sqlProblem("WITH x AS (SELECT 1) SELECT * FROM x")).toBeNull()
    expect(sqlProblem("select 1;")).toBeNull()
    expect(sqlProblem("DELETE FROM tb_place_info")).toMatch(/only SELECT/)
    expect(sqlProblem("SELECT 1; DROP TABLE tb_place_info")).toMatch(/one statement/)
    expect(sqlProblem("SELECT * FROM t WHERE name = 'x; drop table y'")).toBeNull() // literal stripped
    expect(sqlProblem("SELECT load_extension('x')")).toMatch(/forbidden function/)
    expect(sqlProblem("SELECT pg_read_file('/etc/passwd')")).toMatch(/forbidden function/)
    expect(sqlProblem("SELECT * FROM t FOR UPDATE")).toMatch(/forbidden keyword|row locks/)
    expect(sqlProblem("SELECT * FROM t FOR SHARE")).toMatch(/row locks/)
    expect(sqlProblem("PRAGMA table_info(t)")).toMatch(/only SELECT/)
    expect(sqlProblem("SELECT 1 -- ; DROP")).toBeNull()
    expect(sqlProblem("")).toMatch(/empty/)
    expect(stripLiterals(`SELECT 'a''b', "c" FROM t /* x */ -- y`).replace(/\s+/g, " ").trim()).toBe(`SELECT '', "" FROM t`)
  })

  test("withLimit appends a LIMIT only when none is present", () => {
    expect(withLimit("SELECT 1", 50)).toBe("SELECT 1\nLIMIT 51")
    expect(withLimit("SELECT 1 LIMIT 5;", 50)).toBe("SELECT 1 LIMIT 5")
  })
})

describe("format / schema / postgres helpers", () => {
  test("formatRows caps rows and cells and appends a hint", () => {
    const rows = Array.from({ length: 60 }, (_, i) => [i, "x".repeat(200), null])
    const text = formatRows({ columns: ["n", "long", "nul"], rows }, { maxRows: 50, maxCell: 20, maxTokens: 400 })
    expect(text.split("\n")[0]).toBe("n\tlong\tnul")
    expect(text).toContain("50+ rows (more exist)")
    expect(text).toContain("long columns truncated: long")
    expect(text).toContain("NULL")
    expect(estimateTokens(text)).toBeLessThanOrEqual(450)
  })

  test("schema file: table list and one-table description stay small", () => {
    const schema = loadSchema(wt.worktree, join(FIXTURE, "data", "schema.json"))!
    expect(Object.keys(schema.tables).length).toBe(6)
    const list = tableList(schema)
    expect(list).toContain("tb_place_info")
    expect(estimateTokens(list)).toBeLessThanOrEqual(400)
    const t = describeTable(schema, "tb_place_info")
    expect(t).toContain("livestock_types")
    expect(t).toContain("values: 경기|충남")
    expect(estimateTokens(t)).toBeLessThanOrEqual(600)
    expect(describeTable(schema, "nope")).toContain('unknown table "nope"')
  })

  test("postgres helpers: loopback detection and csv parsing", () => {
    expect(isLoopback(dsnHost("postgresql://u:p@127.0.0.1:5432/db"))).toBe(true)
    expect(isLoopback(dsnHost("postgresql://u:p@10.0.0.5:5432/db"))).toBe(false)
    expect(isLoopback(dsnHost("host=localhost dbname=x"))).toBe(true)
    expect(parseCsv('a,b\n1,"x,y"\n2,"q""r"\n')).toEqual({ columns: ["a", "b"], rows: [["1", "x,y"], ["2", 'q"r']] })
  })
})

describe("sqlite backend + tools on the fixture", () => {
  test("read-only handle answers the fixture questions, dist_m works, writes are impossible", async () => {
    const b = openSqlite(DB)
    const r = await b.query("SELECT count(place_id) AS farm_count FROM tb_place_info WHERE sido = '경기' AND place_type = 'farm'", { timeoutMs: 5000 })
    expect(r.columns).toEqual(["farm_count"])
    expect(r.rows[0]![0]).toBe(22)
    const d = await b.query("SELECT count(*) AS n FROM tb_hpai_outbreak_farm o JOIN tb_place_info p ON dist_m(o.longitude, o.latitude, p.longitude, p.latitude) <= 10000 WHERE o.outbreak_id = 1392", { timeoutMs: 5000 })
    expect(Number(d.rows[0]![0])).toBeGreaterThan(0)
    await expect(b.query("INSERT INTO tb_place_info(place_id, place_type) VALUES ('a00000000','farm')", { timeoutMs: 1000 })).rejects.toThrow()
    b.close()
  })

  test("db_query: agent gating, SQL refusal, result text, per-session cap, readable errors", async () => {
    const deps = makeDeps(client, wt.worktree, dataCfg({ max_queries_per_session: 2 }))
    const tool = createDbQueryTool(deps)
    await expect(tool.execute({ sql: "SELECT 1" }, ctx("worker") as any)).rejects.toThrow(/only available to the data agents/)
    await expect(tool.execute({ sql: "DROP TABLE tb_place_info" }, ctx() as any)).rejects.toThrow(/query refused/)
    const out = (await tool.execute({ sql: "SELECT sido, count(*) AS n FROM tb_place_info GROUP BY sido ORDER BY n DESC" }, ctx() as any)) as { output: string; title?: string }
    expect(out.output.split("\n")[0]).toBe("sido\tn")
    expect(out.output).toMatch(/-- 8 rows/)
    await expect(tool.execute({ sql: "SELECT nope FROM tb_place_info" }, ctx() as any)).rejects.toThrow(/query failed[\s\S]*no such column/)
    await expect(tool.execute({ sql: "SELECT 1" }, ctx() as any)).rejects.toThrow(/limit \(2 per session\)/)
  })

  test("schema_lookup: list, one table, gating, missing file", async () => {
    const deps = makeDeps(client, wt.worktree, dataCfg())
    const tool = createSchemaLookupTool(deps)
    const list = (await tool.execute({}, ctx() as any)) as { output: string }
    expect(list.output).toContain("dialect: sqlite")
    expect(list.output).toContain("tb_visit_history")
    const one = (await tool.execute({ table: "tb_vehicle_risk_daily" }, ctx() as any)) as { output: string }
    expect(one.output).toContain("risk_level TEXT")
    expect(one.output).toContain("values: 낮음|주의|위험")
    await expect(tool.execute({}, ctx("main") as any)).rejects.toThrow(/data agents/)
    const gone = makeDeps(client, wt.worktree, dataCfg({ schema_file: "missing.json" }))
    await expect(createSchemaLookupTool(gone).execute({}, ctx() as any)).rejects.toThrow(/not found/)
  })
})

describe("config hook: data agents + evo-semantic MCP", () => {
  test("nothing is registered without a backend; with sqlite the agents, permissions and MCP appear", async () => {
    const off: any = {}
    await createConfigHook(fakeDeps(wt.worktree))(off)
    expect(off.agent["data-analyst"]).toBeUndefined()
    expect(off.mcp).toBeUndefined()

    const cfg: any = {}
    await createConfigHook(fakeDeps(wt.worktree, dataCfg()))(cfg)
    const a = cfg.agent["data-analyst"]
    expect(a.mode).toBe("all")
    expect(a.steps).toBe(12)
    expect(a.permission.bash).toBe("deny")
    expect(a.permission.read).toBe("deny")
    expect(a.permission.db_query).toBeUndefined()
    expect(a.permission["evo-semantic_*"]).toBe("deny")
    expect(a.permission["evo-semantic_resolve_semantics"]).toBe("allow")
    // last-match-wins: the allow keys must come after the wildcard deny
    const keys = Object.keys(a.permission)
    expect(keys.indexOf("evo-semantic_*")).toBeLessThan(keys.indexOf("evo-semantic_resolve_semantics"))
    expect(cfg.agent.worker.permission.db_query).toBe("deny")
    expect(cfg.agent.main.permission.schema_lookup).toBe("deny")
    expect(cfg.agent.main.permission["evo-semantic_*"]).toBe("deny")
    expect(cfg.agent["data-verifier"].permission.db_query).toBe("deny")
    const mcp = cfg.mcp["evo-semantic"]
    expect(mcp.type).toBe("local")
    expect(mcp.command[0]).toBe("python3")
    expect(mcp.command[1]).toBe(vendoredEvoServer())
    expect(existsSync(mcp.command[1])).toBe(true)
    expect(mcp.command[3]).toBe(join(FIXTURE, ".evoontology"))
  })

  test("MCP is skipped (with a log) when the workspace has no active.json", async () => {
    const logs: { msg: string }[] = []
    const cfg: any = {}
    mkdirSync(join(wt.worktree, "empty-ws"))
    await createConfigHook(fakeDeps(wt.worktree, dataCfg({ evo: { enabled: true, workspace: "empty-ws", python: "python3", server: "" } }), logs))(cfg)
    expect(cfg.mcp).toBeUndefined()
    expect(logs.some((l) => l.msg.includes("no active.json"))).toBe(true)
    expect(cfg.agent["data-analyst"]).toBeDefined()
  })
})

